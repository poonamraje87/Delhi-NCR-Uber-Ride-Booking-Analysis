DROP DATABASE IF EXISTS uber_ride_and_demand;
CREATE DATABASE IF NOT EXISTS uber_ride_and_demand;

USE uber_ride_and_demand;

SELECT * FROM ncr_ride_bookings;



/* 
Q1. How many total bookings were made?
*/
SELECT COUNT(*) AS total_bookings
FROM ncr_ride_bookings;

/* 
Q2. How many rides were successfully completed?
*/
SELECT COUNT(*) AS completed_rides
FROM ncr_ride_bookings
WHERE `Booking Status` = 'Completed';

/*
 Q3. What percentage of total bookings were successfully completed?
*/
SELECT (COUNT(CASE WHEN `Booking Status` = 'Completed' THEN 1 END) / COUNT(*)) * 100 AS completion_rate
FROM ncr_ride_bookings;


/*
 Q4. What is the total revenue generated from completed rides?
*/
SELECT SUM(`Booking Value`) AS total_revenue
FROM ncr_ride_bookings
WHERE `Booking Status` = 'Completed';

/*
 Q5. What is the average booking value for completed rides?
*/
SELECT ROUND(AVG(`Booking Value`), 2) AS average_booking_value
FROM ncr_ride_bookings
WHERE `Booking Status` = 'Completed';

/* 
Q6. Which vehicle types have the highest number of completed bookings?
*/
SELECT `Vehicle Type`, COUNT(*) AS Total_Bookings
FROM ncr_ride_bookings
WHERE `Booking Status` = 'Completed' 
GROUP BY `Vehicle Type`
ORDER BY Total_Bookings DESC;

/*
Q7. How much revenue was generated by each vehicle type?
 */
SELECT `Vehicle Type`, SUM(`Booking Value`) AS total_revenue
FROM ncr_ride_bookings
WHERE `Booking Status` = 'Completed'
GROUP BY `Vehicle Type`
ORDER BY total_revenue DESC;

/* 
Q8. What is the total distance covered by completed rides, and what is the average ride distance?
*/
SELECT 
    ROUND(SUM(`Ride Distance`)/100000, 2) AS total_ride_distance,
    ROUND(AVG(`Ride Distance`), 2) AS average_ride_distance
FROM ncr_ride_bookings
WHERE `Booking Status` = 'Completed';

/*
 Q9. What are the most common reasons for customers cancelling their rides?
 */
SELECT `Reason for cancelling by Customer`, COUNT(*) AS total_cancellations
FROM ncr_ride_bookings
WHERE `Reason for cancelling by Customer` IS NOT NULL
GROUP BY `Reason for cancelling by Customer`
ORDER BY total_cancellations DESC;

/*
 Q10. What are the most common reasons for drivers cancelling rides?
 */
SELECT `Driver Cancellation Reason`, COUNT(*) AS total_cancellations
FROM ncr_ride_bookings
WHERE `Driver Cancellation Reason` IS NOT NULL
GROUP BY `Driver Cancellation Reason`
ORDER BY total_cancellations DESC;

/*
 Q11. What is the average driver rating across all rides?
 */
SELECT ROUND(AVG(`Driver Ratings`), 2) AS avg_driver_rating
FROM ncr_ride_bookings;

/*
 Q12. What is the average customer rating across all rides?
 */
SELECT ROUND(AVG(`Customer Rating`), 2) AS avg_customer_rating
FROM ncr_ride_bookings;

/* 
Q13. How many rides were cancelled by customers and drivers?
*/
SELECT SUM(CASE WHEN `Booking Status` = 'Cancelled by Customer' THEN 1 ELSE 0 END) AS customer_cancellations,
SUM(CASE WHEN `Booking Status` = 'Cancelled by Driver' THEN 1 ELSE 0 END) AS driver_cancellations
FROM ncr_ride_bookings;

/*
 Q14. Which payment methods are used most frequently by customers?
 */
SELECT `Payment Method`, COUNT(*) AS total_bookings
FROM ncr_ride_bookings
WHERE `Payment Method` IS NOT NULL
GROUP BY `Payment Method` 
ORDER BY total_bookings DESC;

/*
 Q15. Which 10 pickup locations have a ride count higher than the average ride count across all pickup locations?
 */

SELECT `Pickup Location`, COUNT(*) AS total_rides
FROM ncr_ride_bookings
GROUP BY `Pickup Location`
HAVING total_rides > (
    SELECT AVG(ride_count)
    FROM (
        SELECT `Pickup Location`, COUNT(*) AS ride_count
        FROM ncr_ride_bookings
        GROUP BY `Pickup Location`
    ) AS t_avg_location_count
)
ORDER BY total_rides DESC
LIMIT 10;

/*
 Q16. How many rides have an above-average booking value, and what percentage of total rides do they represent?
*/

SELECT 
    COUNT(*) AS rides_above_average,
    ROUND(
        COUNT(*) * 100.0 / (SELECT COUNT(*) FROM ncr_ride_bookings),
        2
    ) AS percentage_of_total
FROM ncr_ride_bookings
WHERE `Booking Value` > (
    SELECT AVG(`Booking Value`)
    FROM ncr_ride_bookings
);